#!/usr/bin/env python3
"""Generate the firmware export table that compiled programs link against.

Inputs:
  firmware/picocalc_studio/src/sdk/picocalc.h   every function prototype is exported
  firmware/picocalc_studio/src/rt/exports.txt   libc / libm / libgcc symbols (`name` or `name=target`)
Outputs:
  firmware/picocalc_studio/src/rt/exports_table.S   sorted {name, address} table: rt_exports[], rt_exports_count
  sdcard/pico-dev/include/picocalc.h                 copy of the SDK header for the on-device compiler

The table is assembly, not C, so it can name libc functions and compiler builtins without
declaring them (no prototype or builtin clashes). Run it after changing either input:
  python tools/gen_exports.py

  python tools/gen_exports.py --sim-out PATH
writes only PATH: the same table for the RV32 simulator runner (tools/host/simfw/pcxrun.c),
with the exports.txt symbols alone (the SDK functions of picocalc.h do not exist there).
"""
import argparse
import re
import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
FW = REPO / "firmware" / "picocalc_studio"
HEADER = FW / "src" / "sdk" / "picocalc.h"
EXTRA = FW / "src" / "rt" / "exports.txt"
OUT = FW / "src" / "rt" / "exports_table.S"
SD_HEADER = REPO / "sdcard" / "pico-dev" / "include" / "picocalc.h"

PROTO = re.compile(r"^[A-Za-z_][\w \t\*]*?\b([A-Za-z_]\w*)\s*\([^;{]*\)[^;{]*;")


def header_functions(text):
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    names = []
    stmt = ""
    for line in text.splitlines():
        s = line.strip()
        if not stmt and (not s or s.startswith("#") or s.startswith("}") or s.startswith("extern \"C\"")):
            continue
        stmt = (stmt + " " + s).strip()
        if not stmt.endswith(";") and not stmt.endswith("}") and not stmt.endswith("{"):
            continue
        m = PROTO.match(stmt)
        if m and not stmt.startswith(("typedef", "struct", "enum", "union")):
            names.append(m.group(1))
        stmt = ""
    return names


def extra_symbols(text):
    out = []
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        name, _, target = line.partition("=")
        out.append((name.strip(), (target or name).strip()))
    return out


def table_source(entries, title):
    names = sorted(entries, key=lambda n: n.encode())
    out = [
        title,
        "/* Do not edit. Sorted by name (byte order) for rt_find_export()'s binary search. */",
        "",
        '    .section .rodata.rt_exports, "a"',
        "    .balign 4",
        "    .global rt_exports",
        "rt_exports:",
    ]
    for i, n in enumerate(names):
        out.append(f"    .word .Ls{i}, {entries[n]}")
    out += [
        "",
        "    .global rt_exports_count",
        "    .balign 4",
        "rt_exports_count:",
        f"    .word {len(names)}",
        "",
        '    .section .rodata.rt_export_names, "aMS", @progbits, 1',
    ]
    for i, n in enumerate(names):
        out.append(f'.Ls{i}: .asciz "{n}"')
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sim-out", help="write only the simulator table (exports.txt symbols) here")
    a = ap.parse_args()
    entries = {}
    if not a.sim_out:
        for name in header_functions(HEADER.read_text()):
            entries[name] = name
    for name, target in extra_symbols(EXTRA.read_text()):
        if name in entries:
            sys.exit(f"gen_exports: {name} exported twice")
        entries[name] = target

    if a.sim_out:
        sim = Path(a.sim_out)
        sim.parent.mkdir(parents=True, exist_ok=True)
        sim.write_text(table_source(
            entries, "/* GENERATED by tools/gen_exports.py --sim-out from exports.txt (simulator table). */"),
            newline="\n")
        return

    names = entries
    OUT.write_text(table_source(
        entries, "/* exports_table.S - GENERATED by tools/gen_exports.py from picocalc.h and exports.txt. */"),
        newline="\n")

    SD_HEADER.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(HEADER, SD_HEADER)
    print(f"gen_exports: {len(names)} symbols -> {OUT.relative_to(REPO)}, header -> {SD_HEADER.relative_to(REPO)}")


if __name__ == "__main__":
    main()
